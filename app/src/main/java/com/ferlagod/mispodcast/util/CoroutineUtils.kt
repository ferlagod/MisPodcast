package com.ferlagod.mispodcast.util

import kotlin.coroutines.cancellation.CancellationException

/**
 * Relanza la cancelación de la corrutina al capturar [Exception] o [Throwable] de forma genérica,
 * para no romper la concurrencia estructurada (un trabajo cancelado debe detenerse, no seguir como si fallara).
 */
fun Throwable.rethrowIfCancellation() {
    if (this is CancellationException) throw this
}
